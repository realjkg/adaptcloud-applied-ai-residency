// Apply a change to the simulated tenant, destroy it, and compare the tenant before and after. It lives in its own file so the
// browser's jobs can run it without loading the live transport that the command-line tool imports.
import { LabTransport } from "./lab-transport.mjs";
import { apply, destroy, plan, prepare } from "./provision.mjs";
import { stableStringify } from "./provision-policy.mjs";
import { SIMULATION_POLICY } from "./simulation-policy.mjs";

/**
 * Applies and destroys the whole twin against a simulated tenant that already holds objects it does not own,
 * then compares the tenant before and after. The approvals here are generated by this function for the
 * simulator only; a real approval is written by a person.
 */
export async function runRoundtrip(config, now = new Date()) {
  const prepared = prepare(config);
  if (!prepared.ok) return prepared;
  const { changeset, digest } = prepared;
  const transport = new LabTransport();
  transport.seedUnmanaged({ vendor: "paloalto", object: "zone", name: "legacy-dmz" }, { note: "not ours" });
  transport.seedUnmanaged({ vendor: "f5", object: "pool", name: "legacy-pool" }, { note: "not ours" });
  const before = transport.snapshot();

  const target = { environment: "lab", tenantId: "lab-tenant-001", owner: config.twinId };
  const approval = (action) => ({ ref: `SIM-${action.toUpperCase()}-0001`, approver: "simulation", action, tenantId: target.tenantId, digest, approvedAt: now.toISOString() });

  const planned = await plan({ changeset, transport, policy: SIMULATION_POLICY, target });
  const applied = await apply({ changeset, transport, policy: SIMULATION_POLICY, target, approval: approval("apply"), plannedDigest: planned.digest, now });
  const afterApply = transport.snapshot();
  const destroyed = await destroy({ changeset, transport, policy: SIMULATION_POLICY, target, approval: approval("destroy"), now });
  const afterDestroy = transport.snapshot();

  return {
    ok: planned.ok && applied.ok && destroyed.ok,
    objects: { before: before.length, afterApply: afterApply.length, afterDestroy: afterDestroy.length },
    created: applied.created,
    deleted: destroyed.deleted,
    symmetric: stableStringify(before) === stableStringify(afterDestroy),
    unmanagedSurvived: before.every((entry) => afterDestroy.some((item) => item.name === entry.name && item.managedBy === null))
  };
}
